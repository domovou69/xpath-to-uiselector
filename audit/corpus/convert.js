#!/usr/bin/env node
// npm run corpus:convert — the converter over the R corpus, offline (PLAN.md
// stage 4a). Writes audit/corpus/convert-summary.md.
//
// Each Android literal (kinds xpath and xpath-dynamic) is read the way the
// scanner reads it: decoded for its language and quote kind, runtime parts as
// placeholders, then converted. The strategy column says what the scanner
// would do with the call around it. No device: whether the conversions select
// the same elements is the fuzz run's job (stage 4b).
const { writeFileSync } = require('fs');
const { join } = require('path');
const corpus = require('./android-locators.json');
const STATUS = require('../../lib/status');
const { convertXpathToUiSelector } = require('../../lib/converter');
const { literalKind, decodeLiteral, decrementHoles } = require('../../lib/literal');
const { rewriteStrategy } = require('../../lib/strategy');

const EXT = { Java: '.java', Kotlin: '.kt', Python: '.py', 'C#': '.cs', TypeScript: '.ts', JavaScript: '.js' };

// The literal as the scanner reads it: { value, placeholders }, or null.
function decodeEntry(e) {
  // The corpus keeps no string prefix: braces in Python / C# literals are read
  // as f-string / $"" holes, as the corpus build counts them dynamic.
  const braces = /\{\w*\}/.test(e.source);
  const prefix = braces ? (e.lang === 'Python' ? 'f' : e.lang === 'C#' ? '$' : '') : '';
  const kind = literalKind(EXT[e.lang], e.quote, prefix);
  const decoded = decodeLiteral(e.source, kind, e.quote);
  return decoded && { ...decoded, kind };
}

function convertEntry(e) {
  const decoded = decodeEntry(e);
  if (!decoded) return { outcome: 'skip', reason: 'the string literal has an escape this tool does not read' };
  const keys = new Set(decoded.placeholders.keys());
  const decrement = decrementHoles(decoded.placeholders, decoded.kind, decoded.free);
  const res = convertXpathToUiSelector(decoded.value, { placeholders: keys, decrement });
  if (res.status !== STATUS.SUCCESS) return { outcome: res.status === STATUS.SKIPPED_IOS ? 'ios' : 'skip', reason: res.reason, hint: res.hint };
  const warnings = res.warning ? res.warning.split('; ') : [];
  return { outcome: warnings.length ? 'close' : 'exact', warnings, xpath: decoded.value, uiselector: res.locator, placeholders: decoded.placeholders, decrement };
}

// What the scanner does with the call around a converted literal.
function strategyAction(e) {
  if (!e.strategy) return e.lang === 'TypeScript' || e.lang === 'JavaScript' ? 'written (WebdriverIO android=)' : 'reported (no strategy call)';
  return rewriteStrategy(e.strategy, EXT[e.lang], '') ? 'written (strategy rewritten)' : 'reported (strategy without UiAutomator form)';
}

const WARNING_LABEL = {
  'findElements returns at most one match per container': 'childSelector (//A//B)',
  'elements with no class name also appear as android.view.View in the page source': 'android.view.View',
};
const warningLabel = w => WARNING_LABEL[w] || (w.startsWith('a runtime value goes into index') ? 'runtime index'
  : w.startsWith('a runtime value') ? 'runtime value in a literal' : w.startsWith('a runtime class name') ? 'runtime class name'
    : w.startsWith('a runtime position') ? 'runtime position' : w.startsWith('a range widget') ? 'range widget (a number in the text)'
      : w.startsWith('Android regexes') ? 'lower-case()' : w);

// Reasons that differ only in an attribute name are counted together.
const reasonGroup = r => (/ has no UiSelector criterion$/.test(r) ? 'an attribute without a UiSelector criterion (bounds, displayed, …)'
  : / is a web or iOS attribute/.test(r) ? 'a web or iOS attribute (label, id, value, data-*, …)'
  : /^the page source has no .* attribute/.test(r) ? 'an alias attribute (name, resourceId, …) that the page source does not have'
    : /^not a valid XPath/.test(r) ? 'not a valid XPath' : r);

function run() {
  const android = corpus.filter(e => e.kind === 'xpath' || e.kind === 'xpath-dynamic');
  const rows = android.map(e => ({ e, ...convertEntry(e) }));
  const occ = list => list.reduce((n, r) => n + r.e.count, 0);
  const pct = (a, b) => `${((100 * a) / b).toFixed(1)} %`;
  const projects = [...new Set(android.map(e => e.project))];
  // Project-weighted: each project counts 1, split over its literals.
  const weighted = pick => {
    let sum = 0;
    for (const p of projects) {
      const mine = rows.filter(r => r.e.project === p);
      sum += mine.filter(pick).length / mine.length;
    }
    return `${((100 * sum) / projects.length).toFixed(1)} %`;
  };
  const total = rows.length;
  const totalOcc = occ(rows);
  const line = (label, pick) => {
    const hit = rows.filter(pick);
    return `| ${label} | ${hit.length} | ${pct(hit.length, total)} | ${occ(hit)} | ${pct(occ(hit), totalOcc)} | ${weighted(pick)} |`;
  };

  const out = [];
  out.push('# R corpus through the converter (offline)', '');
  out.push(`Generated by \`npm run corpus:convert\` (audit/corpus/convert.js) from [android-locators.json](android-locators.json):`);
  out.push(`${total} Android literals (kinds xpath and xpath-dynamic, ${rows.filter(r => r.e.kind === 'xpath-dynamic').length} dynamic) from ${projects.length} projects.`);
  out.push('No device: this counts what the converter does, not whether it is right. The emulator fuzz run (stage 4b) checks');
  out.push('the conversions. Unique = one literal per project, occurrences = every place in the source files, project-weighted =');
  out.push('every project counts the same.', '');

  out.push('## Outcome', '');
  out.push('| Outcome | Unique | Share | Occurrences | Share | Project-weighted |', '| --- | --- | --- | --- | --- | --- |');
  out.push(line('exact', r => r.outcome === 'exact'));
  out.push(line('close (converted with a warning)', r => r.outcome === 'close'));
  out.push(line('skip', r => r.outcome === 'skip'));
  out.push(line('iOS (XCUIElementType inside an Android-looking literal)', r => r.outcome === 'ios'));
  out.push('');

  out.push('## Warnings of the close conversions', '');
  out.push('A conversion can carry more than one warning.', '');
  const close = rows.filter(r => r.outcome === 'close');
  const byWarning = new Map();
  for (const r of close) for (const w of new Set(r.warnings.map(warningLabel))) byWarning.set(w, [...(byWarning.get(w) || []), r]);
  out.push('| Warning | Unique | Share of all | Occurrences |', '| --- | --- | --- | --- |');
  for (const [w, list] of [...byWarning].sort((a, b) => b[1].length - a[1].length)) out.push(`| ${w} | ${list.length} | ${pct(list.length, total)} | ${occ(list)} |`);
  out.push('');

  out.push('## Top reasons to skip', '');
  const skipped = rows.filter(r => r.outcome === 'skip');
  const byReason = new Map();
  for (const r of skipped) byReason.set(reasonGroup(r.reason), [...(byReason.get(reasonGroup(r.reason)) || []), r]);
  const hinted = skipped.filter(r => r.hint);
  out.push(`${skipped.length} skipped literals; the first reason the converter meets is counted. ${hinted.length} of them (${occ(hinted)} occurrences)`);
  out.push('carry a `hint`: how to rewrite the locator by hand and how the nearest UiSelector form differs.', '');
  out.push('| Reason | Unique | Share of all | Occurrences | Projects |', '| --- | --- | --- | --- | --- |');
  const sorted = [...byReason].sort((a, b) => b[1].length - a[1].length);
  for (const [reason, list] of sorted.slice(0, 15)) {
    out.push(`| ${reason} | ${list.length} | ${pct(list.length, total)} | ${occ(list)} | ${new Set(list.map(r => r.e.project)).size} |`);
  }
  const rest = sorted.slice(15);
  if (rest.length) out.push(`| ${rest.length} other reasons | ${rest.reduce((n, [, l]) => n + l.length, 0)} | | | |`);
  out.push('');

  out.push('## What the scanner does with a converted literal', '');
  out.push('From the strategy call recorded with each literal (PLAN.md section 2).', '');
  const converted = rows.filter(r => r.outcome === 'exact' || r.outcome === 'close');
  const byAction = new Map();
  for (const r of converted) byAction.set(strategyAction(r.e), [...(byAction.get(strategyAction(r.e)) || []), r]);
  out.push('| Action | Unique | Share of converted | Occurrences |', '| --- | --- | --- | --- |');
  for (const [a, list] of [...byAction].sort((x, y) => y[1].length - x[1].length)) out.push(`| ${a} | ${list.length} | ${pct(list.length, converted.length)} | ${occ(list)} |`);
  out.push('');

  out.push('## By language', '');
  out.push('| Language | Literals | Exact | Close | Skip |', '| --- | --- | --- | --- | --- |');
  for (const lang of Object.keys(EXT)) {
    const mine = rows.filter(r => r.e.lang === lang);
    if (!mine.length) continue;
    const n = o => pct(mine.filter(r => r.outcome === o).length, mine.length);
    out.push(`| ${lang} | ${mine.length} | ${n('exact')} | ${n('close')} | ${n('skip')} |`);
  }
  out.push('');

  writeFileSync(join(__dirname, 'convert-summary.md'), `${out.join('\n')}\n`);
  return { rows, total };
}

if (require.main === module) {
  const { rows, total } = run();
  const c = o => rows.filter(r => r.outcome === o).length;
  console.log(`${total} Android literals: ${c('exact')} exact, ${c('close')} close, ${c('skip')} skip, ${c('ios')} iOS → audit/corpus/convert-summary.md`);
}

module.exports = { decodeEntry, convertEntry, run, WARNING_LABEL, warningLabel };
